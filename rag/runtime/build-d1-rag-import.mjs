#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));

function findRagRoot(start) {
  let current = resolve(start);
  for (;;) {
    if (current.endsWith(`${process.platform === 'win32' ? '\\' : '/'}rag`) || current.split(/[\\/]/).at(-1) === 'rag') {
      return current;
    }
    const parent = dirname(current);
    if (parent === current) break;
    current = parent;
  }
  throw new Error('Could not locate rag/ root from this script.');
}

const RAG_ROOT = findRagRoot(SCRIPT_DIR);
const CORPUS_DIR = join(RAG_ROOT, 'rag-corpus');
const INPUT = join(CORPUS_DIR, 'retrieval-documents-v2', 'documents.jsonl');
const OUTPUT_DIR = join(CORPUS_DIR, 'd1-runtime-v1');
const OUTPUT_SQL = join(OUTPUT_DIR, 'rag-documents.sql');
const OUTPUT_REPORT = join(OUTPUT_DIR, 'd1-import-validation-report.txt');
const EXPECTED_DOCUMENTS = 2808;
const EXPECTED_REPOSITORIES = 134;

function sha256(buffer) {
  return createHash('sha256').update(buffer).digest('hex');
}

function sqlString(value) {
  if (value === null || value === undefined) return 'NULL';
  const text = String(value);
  if (text.includes('\0')) throw new Error('NUL byte cannot be written to SQL text.');
  return `'${text.replaceAll("'", "''")}'`;
}

function sqlJson(value) {
  return sqlString(JSON.stringify(value ?? []));
}

function integer(value, fallback = 0) {
  const result = Number(value);
  if (!Number.isInteger(result)) return fallback;
  return result;
}

function real(value, fallback = 0) {
  const result = Number(value);
  return Number.isFinite(result) ? result : fallback;
}

async function main() {
  console.log('Portfolio GitHub RAG — build D1 runtime evidence import v1');
  console.log(`RAG root: ${RAG_ROOT}`);
  console.log('');

  const inputBytes = await readFile(INPUT);
  const inputSha = sha256(inputBytes);
  const lines = inputBytes.toString('utf8').split(/\r?\n/).filter((line) => line.trim());
  const documents = lines.map((line, index) => {
    try {
      return JSON.parse(line);
    } catch (error) {
      throw new Error(`Invalid JSON at documents.jsonl line ${index + 1}: ${error instanceof Error ? error.message : String(error)}`, { cause: error });
    }
  });

  if (documents.length !== EXPECTED_DOCUMENTS) {
    throw new Error(`Expected ${EXPECTED_DOCUMENTS} documents, found ${documents.length}.`);
  }

  const ids = new Set();
  const repositories = new Set();
  let schemaVersion = null;

  for (const [index, doc] of documents.entries()) {
    const id = String(doc.document_id ?? '').trim();
    if (!id) throw new Error(`Document ${index + 1} has no document_id.`);
    if (ids.has(id)) throw new Error(`Duplicate document_id: ${id}`);
    ids.add(id);

    const repositoryIndex = integer(doc.repository_index, -1);
    if (repositoryIndex <= 0) throw new Error(`${id}: invalid repository_index.`);
    repositories.add(repositoryIndex);

    const text = String(doc.text ?? '');
    if (!text.trim()) throw new Error(`${id}: authoritative text is empty.`);

    const currentSchema = String(doc.document_schema_version ?? '').trim();
    if (!currentSchema) throw new Error(`${id}: document_schema_version missing.`);
    if (schemaVersion === null) schemaVersion = currentSchema;
    if (schemaVersion !== currentSchema) {
      throw new Error(`${id}: mixed document schema versions (${schemaVersion} vs ${currentSchema}).`);
    }
  }

  if (repositories.size !== EXPECTED_REPOSITORIES) {
    throw new Error(`Expected ${EXPECTED_REPOSITORIES} repositories, found ${repositories.size}.`);
  }

  await rm(OUTPUT_DIR, { recursive: true, force: true });
  await mkdir(OUTPUT_DIR, { recursive: true });

  const statements = [
    '-- Generated by rag/runtime/build-d1-rag-import.mjs. Do not hand-edit.',
    '-- Source: rag/rag-corpus/retrieval-documents-v2/documents.jsonl',
    'DELETE FROM rag_documents;',
    'DELETE FROM rag_corpus_meta;',
  ];

  for (const doc of documents) {
    statements.push(
      `INSERT INTO rag_documents (` +
        `document_id,repository_index,repository_name,repository_slug,repository_url,` +
        `retrieval_class,semantic_area,evidence_polarity,evidence_level,specificity_score,` +
        `concrete_signal_count,word_count,text,topics_json,evidence_areas_json,` +
        `related_skill_ratings_json,source_fragments_json,provenance_json` +
      `) VALUES (` +
        [
          sqlString(doc.document_id),
          integer(doc.repository_index),
          sqlString(doc.repository_name ?? ''),
          sqlString(doc.repository_slug ?? null),
          sqlString(doc.repository_url ?? null),
          sqlString(doc.retrieval_class ?? 'unknown'),
          sqlString(doc.semantic_area ?? 'unknown'),
          sqlString(doc.evidence_polarity ?? 'neutral'),
          sqlString(doc.evidence_level ?? 'unknown'),
          real(doc.specificity_score),
          integer(doc.concrete_signal_count),
          integer(doc.word_count),
          sqlString(doc.text),
          sqlJson(doc.topics),
          sqlJson(doc.evidence_areas),
          sqlJson(doc.related_skill_ratings),
          sqlJson(doc.source_fragments),
          sqlJson(doc.provenance ?? {}),
        ].join(',') +
      `);`,
    );
  }

  statements.push(
    `INSERT INTO rag_corpus_meta (` +
      `corpus_key,document_count,repository_count,documents_sha256,document_schema_version,imported_at` +
    `) VALUES (` +
      [
        sqlString('portfolio-career-rag-v1'),
        EXPECTED_DOCUMENTS,
        EXPECTED_REPOSITORIES,
        sqlString(inputSha),
        sqlString(schemaVersion),
        sqlString(new Date().toISOString()),
      ].join(',') +
    `);`,
    '',
  );

  await writeFile(OUTPUT_SQL, statements.join('\n'), 'utf8');

  const report = [
    'Portfolio GitHub RAG — D1 runtime evidence import v1',
    '====================================================',
    '',
    'STATUS: PASS',
    '',
    `Input: ${INPUT}`,
    `Input SHA-256: ${inputSha}`,
    `Documents: ${documents.length}/${EXPECTED_DOCUMENTS}`,
    `Unique document IDs: ${ids.size}/${EXPECTED_DOCUMENTS}`,
    `Repositories: ${repositories.size}/${EXPECTED_REPOSITORIES}`,
    `Document schema version: ${schemaVersion}`,
    '',
    'OUTPUT',
    `  ${OUTPUT_SQL}`,
    '',
    'NEXT',
    '  npm run db:migrate:remote',
    '  npm run rag:d1:import:remote',
    '',
  ].join('\n');

  await writeFile(OUTPUT_REPORT, report, 'utf8');

  console.log(`SUCCESS (${documents.length} documents; ${repositories.size} repositories)`);
  console.log(`Input SHA-256: ${inputSha}`);
  console.log('');
  console.log('OUTPUT');
  console.log(`  ${OUTPUT_SQL}`);
  console.log(`  ${OUTPUT_REPORT}`);
}

main().catch((error) => {
  console.error('');
  console.error('D1 RAG IMPORT BUILD: FAILED');
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
